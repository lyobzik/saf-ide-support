/**
 * Признак Jinja-значения. Вынесен отдельно, чтобы им могли пользоваться и
 * ссылочная логика, и определение целевой формы, не завися от лексера.
 *
 * Значения с `{{`/`{%` не порождают прямых ссылок на сущности: динамический
 * шаблон — не «битая ссылка», предупреждать по нему нельзя.
 */
export function isJinja(text: string): boolean {
  return text.includes("{{") || text.includes("{%");
}
