/**
 * Грамматика идентификатора Jinja — единственное определение на всё расширение.
 *
 * Зовут её двое: лексер (`jinjaLexer.ts`) при токенизации выражения и фильтр
 * имён модели пользователя. Две копии разошлись бы: раньше лексер приближал
 * `Character.isJavaIdentifierStart/Part` диапазонами `[A-Za-z_$À-￿]`, и по этому
 * приближению `×` (U+00D7), `÷` (U+00F7) и одиночный суррогат оказывались
 * идентификаторами, а в плагине — нет.
 *
 * Определение — через **категории Unicode**, а не через удобные методы
 * платформы: `str.isdigit()` в Python принимает `²` (категория `No`), а
 * `\p{Nd}` и `Character.isDigit` — нет.
 *
 * Область определения — **только BMP**. Символ вне BMP (`𐐀`, U+10400)
 * идентификатором не является по контракту: при посимвольном обходе Kotlin
 * видит там две UTF-16-единицы, JS — тоже две, Python — один code point, и без
 * ограничения результат зависел бы от способа обхода. Здесь это выходит само:
 * обход идёт по code unit, и половинки суррогатной пары (категория `Cs`) не
 * проходят ни одну проверку.
 */

const LETTER = /\p{L}/u;
const DECIMAL_DIGIT = /\p{Nd}/u;

/**
 * Аргумент — ровно одна UTF-16-единица. Проверка несёт обе гарантии сразу и
 * потому обязательна:
 *
 * 1. **длина.** Без неё регулярка ищет букву в любой позиции, и `"ab"`, `"a9"`,
 *    даже `"-x"` проходят как один идентификатор;
 * 2. **BMP.** Символ вне BMP — суррогатная пара длины 2, и до проверки
 *    категории он не доходит.
 *
 * Якоря в регулярках роли не играют и потому не ставятся: при одной единице
 * `/\p{L}/u` и `/^\p{L}$/u` эквивалентны (мутант со снятыми якорями выживает),
 * а второй пункт они не закрывают вовсе — `/^\p{L}$/u` матчит `𐐀` целиком,
 * потому что с флагом `u` шаблон работает по code point'ам. Отдельной проверки
 * на `<= 0xFFFF` тоже не нужно: у одной единицы код по построению в этом
 * диапазоне.
 */
const isSingleUnit = (c: string): boolean => c.length === 1;

/** Начало идентификатора: `_` или буква (категория `L*`). Аргумент — одна UTF-16-единица. */
export function isIdentifierStart(c: string): boolean {
  if (!isSingleUnit(c)) return false;
  return c === "_" || LETTER.test(c);
}

/** Продолжение идентификатора: начало плюс десятичная цифра (категория `Nd`). */
export function isIdentifierPart(c: string): boolean {
  if (!isSingleUnit(c)) return false;
  return isIdentifierStart(c) || DECIMAL_DIGIT.test(c);
}

/**
 * Адресуемо ли [name] как один сегмент Jinja (`user.<name>`).
 *
 * Обход — по UTF-16-единицам, как в лексере: имя из символов вне BMP
 * адресуемым не считается.
 */
export function isAddressableName(name: string): boolean {
  if (name.length === 0) return false;
  if (!isIdentifierStart(name[0] as string)) return false;
  for (let i = 1; i < name.length; i++) {
    if (!isIdentifierPart(name[i] as string)) return false;
  }
  return true;
}
